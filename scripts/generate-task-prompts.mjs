import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const definitions = JSON.parse(
  await readFile(path.join(projectRoot, "tasks", "task-definitions.json"), "utf8")
);
const outputPath = path.join(projectRoot, "lib", "generated-task-prompts.ts");

const imports = definitions.tasks
  .map((task, index) => `import prompt${index} from "@/tasks/${task.id}/prompt.md";`)
  .join("\n");
const entries = definitions.tasks
  .map((task, index) => `  ${JSON.stringify(task.id)}: prompt${index}`)
  .join(",\n");

await writeFile(
  outputPath,
  `// Generated by scripts/generate-task-prompts.mjs. Do not edit manually.\n${imports}\n\nexport const taskPrompts: Record<string, string> = {\n${entries}\n};\n`
);
